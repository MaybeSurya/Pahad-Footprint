type NestedKeys<T> = T extends object
  ? { [K in keyof T]: `${string & K}${"" extends NestedKeys<T[K]> ? "" : "."}${NestedKeys<T[K]>}` }[keyof T]
  : "";

export type TranslationKey = NestedKeys<typeof translations.EN>;

export function getNestedTranslation(obj: any, path: string): string | undefined {
  const parts = path.split('.');
  let current: any = obj;
  for (const part of parts) {
    if (current === undefined || current === null) {
      return undefined;
    }
    current = current[part];
  }
  return current;
}
